# src/eval_utils.py
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional


METRIC_ALIASES = {
    "revenue": [
        "revenue", "net sales", "sales", "total net sales"
    ],
    "net_income": [
        "net income", "net earnings", "profit"
    ],
    "eps": [
        "eps",
        "earnings per share",
        "diluted earnings per share",
        "diluted eps",
        "basic earnings per share",
    ],
    "operating_income": [
        "operating income", "income from operations"
    ],
    "gross_margin": [
        "gross margin"
    ],
    "cash_flow": [
        "cash flow", "operating cash flow", "cash generated by operating activities"
    ],
    "r_and_d": [
        "research and development", "r&d"
    ],
}


def load_json(path: Path) -> Any:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def save_json(obj: Any, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)


def normalize_text(text: str) -> str:
    return re.sub(r"\s+", " ", text.lower()).strip()


def extract_number_tokens(text: str) -> List[str]:
    """
    Examples:
    $42.4
    42.4
    16%
    1.42
    """
    text = text.replace(",", "")
    pattern = r"\$?\d+(?:\.\d+)?%?"
    return re.findall(pattern, text)


def normalize_number_token(token: str) -> Optional[float]:
    token = token.replace("$", "").replace("%", "").replace(",", "").strip()
    try:
        return float(token)
    except ValueError:
        return None


def detect_metrics(text: str) -> List[str]:
    text_n = normalize_text(text)
    found = []

    for metric, aliases in METRIC_ALIASES.items():
        if any(alias in text_n for alias in aliases):
            found.append(metric)

    return found


def metric_overlap(claim_text: str, evidence_text: str) -> Dict[str, Any]:
    claim_metrics = set(detect_metrics(claim_text))
    evidence_metrics = set(detect_metrics(evidence_text))
    overlap = claim_metrics.intersection(evidence_metrics)

    return {
        "claim_metrics": sorted(claim_metrics),
        "evidence_metrics": sorted(evidence_metrics),
        "overlap_metrics": sorted(overlap),
        "metric_match": len(overlap) > 0,
    }


def number_overlap(claim_text: str, evidence_text: str, tolerance: float = 0.0) -> Dict[str, Any]:
    claim_tokens = extract_number_tokens(claim_text)
    evidence_tokens = extract_number_tokens(evidence_text)

    claim_nums = [normalize_number_token(x) for x in claim_tokens]
    evidence_nums = [normalize_number_token(x) for x in evidence_tokens]

    claim_nums = [x for x in claim_nums if x is not None]
    evidence_nums = [x for x in evidence_nums if x is not None]

    matched_pairs = []
    for cn in claim_nums:
        for en in evidence_nums:
            if abs(cn - en) <= tolerance:
                matched_pairs.append((cn, en))

    return {
        "claim_number_tokens": claim_tokens,
        "evidence_number_tokens": evidence_tokens,
        "claim_numbers": claim_nums,
        "evidence_numbers": evidence_nums,
        "matched_pairs": matched_pairs,
        "number_match": len(matched_pairs) > 0,
    }


def rule_precheck(claim_text: str, evidence_text: str) -> Dict[str, Any]:
    metric_info = metric_overlap(claim_text, evidence_text)
    number_info = number_overlap(claim_text, evidence_text)

    if metric_info["metric_match"] and number_info["number_match"]:
        label = "supported"
    elif metric_info["metric_match"] or number_info["number_match"]:
        label = "partially_supported"
    else:
        label = "not_supported"

    return {
        "rule_label": label,
        "metric_info": metric_info,
        "number_info": number_info,
    }


def hit_at_k(labels: List[str], k: int) -> int:
    return int("supported" in labels[:k])


def partial_hit_at_k(labels: List[str], k: int) -> int:
    return int(any(x in ("supported", "partially_supported") for x in labels[:k]))


def reciprocal_rank(labels: List[str]) -> float:
    for i, label in enumerate(labels, start=1):
        if label == "supported":
            return 1.0 / i
    return 0.0


def precision_at_k(labels: List[str], k: int) -> float:
    topk = labels[:k]
    if not topk:
        return 0.0
    supported_count = sum(1 for x in topk if x == "supported")
    return supported_count / len(topk)


def summarize_retrieval_eval(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    if not records:
        return {}

    hit1 = 0
    hit3 = 0
    phit3 = 0
    mrr_total = 0.0
    p_at_3_total = 0.0

    for r in records:
        labels = r["judge_labels"]
        hit1 += hit_at_k(labels, 1)
        hit3 += hit_at_k(labels, 3)
        phit3 += partial_hit_at_k(labels, 3)
        mrr_total += reciprocal_rank(labels)
        p_at_3_total += precision_at_k(labels, 3)

    n = len(records)
    return {
        "num_claims": n,
        "hit@1": round(hit1 / n, 4),
        "hit@3": round(hit3 / n, 4),
        "partial_hit@3": round(phit3 / n, 4),
        "mrr": round(mrr_total / n, 4),
        "precision@3": round(p_at_3_total / n, 4),
    }


def summarize_report_eval(records: List[Dict[str, Any]]) -> Dict[str, Any]:
    if not records:
        return {}

    faithful_count = 0
    hallucination_count = 0
    relevance_total = 0.0

    for r in records:
        judge = r["report_judge"]
        if judge["faithfulness"] == "high":
            faithful_count += 1
        if judge["hallucination"]:
            hallucination_count += 1
        relevance_total += float(judge["relevance_score"])

    n = len(records)
    return {
        "num_reports": n,
        "high_faithfulness_rate": round(faithful_count / n, 4),
        "hallucination_rate": round(hallucination_count / n, 4),
        "avg_relevance_score": round(relevance_total / n, 4),
    }